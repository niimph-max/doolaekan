'use client';

import React from 'react';
import type { Book } from '@/lib/types';

/** บรรทัดบนสุดของทุกแท็บ — ชื่อแอป · ชื่อสมุดที่กำลังดูอยู่
 *
 *  เดิมหน้าส่วนใหญ่ขึ้นแค่ "Doolaekan" ทุกแท็บเหมือนกันหมด ซึ่งบอกอะไรไม่ได้เลย
 *  ทั้งที่คำถามที่สำคัญที่สุดตอนกดดูข้อมูลคนอื่นคือ "ตอนนี้ดูสมุดใครอยู่"
 *  โดยเฉพาะเวลาสลับไปมาระหว่างสมุดพ่อ แม่ และของตัวเอง แล้วกดบันทึกอะไรลงไป
 *
 *  หน้าหลักใช้ซ้ำอีกรอบตรงกลางหน้า เหนือปุ่มที่บันทึกอะไรลงสมุดจริงๆ เพราะ
 *  บรรทัดบนสุดเลื่อนพ้นจอไปตั้งแต่การ์ดยาใบที่สอง — จึงต้องเป็นคอมโพเนนต์เดียวกัน
 *  ไม่ใช่ก๊อปข้อความไปวาง ไม่งั้นวันหนึ่งสองที่จะเขียนไม่เหมือนกันแล้วไม่มีใครรู้ */
export function Kicker({ book, style }: { book: Book; style?: React.CSSProperties }) {
  return (
    <p className="kicker" style={style}>
      Doolaekan{book.owner_name ? ` · ${book.owner_name}` : ''}
    </p>
  );
}
